#!/usr/bin/env bash
set -euo pipefail
experiment_dir="${1:?Pass the absolute experiment root}"
cd "$experiment_dir"
export OPAMROOT="$experiment_dir/opam"
export OPAMSWITCH=icra-4.14
eval "$(opam env --root "$OPAMROOT" --switch "$OPAMSWITCH" --set-switch)"
export ICRA_NATIVE_PREFIX=/usr
export LD_LIBRARY_PATH="$experiment_dir/venv/lib/python3.14/site-packages/z3/lib:$OPAMROOT/$OPAMSWITCH/lib/stublibs${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
opam install -y --jobs=1 batteries.3.9.0 dune.3.15.3 ocamlgraph.1.8.8 \
  ppx_deriving.5.2.1 ppxlib.0.35.0 oasis.0.4.11 ocamlbuild menhir \
  mlgmpidl.1.3.0 apron.v0.9.15 zarith camlidl ounit
opam pin add -y --no-action conf-ntl "$experiment_dir/icra-dependencies/local-opam/conf-ntl"
opam pin add -y --no-action cil "$experiment_dir/icra-dependencies/cil-source"
opam pin add -y --no-action OCRS "$experiment_dir/icra-dependencies/ocrs-source"
mkdir -p icra-dependencies/ntl-source
tar -xzf archives/9975d8299d4ee149137b1d5b28238bf8 -C icra-dependencies/ntl-source --strip-components=1
cp "$experiment_dir/ArithExe/experiments/linux/ntl.opam" icra-dependencies/ntl-source/ntl.opam
opam pin add -y --no-action ntl "$experiment_dir/icra-dependencies/ntl-source"
opam install -y --jobs=1 conf-ntl ntl cil OCRS
# Transfer the architecture-independent binding sources already generated by
# Z3 4.15.3's upstream generator, not any Mac object files or libraries.
if ocamlfind query Z3 >/dev/null 2>&1; then
  test "$(ocamlfind query -format '%v' Z3)" = 4.15.3
else
mkdir -p icra-dependencies/z3-bindings
tar -xzf archives/icra-z3-generated.tar.gz -C icra-dependencies/z3-bindings
cd icra-dependencies/z3-bindings
z3_package="$experiment_dir/venv/lib/python3.14/site-packages/z3"
ocamlfind ocamlc -package zarith -i z3enums.ml > z3enums.mli
ocamlfind ocamlc -package zarith -c z3enums.mli
ocamlfind ocamlc -package zarith -c z3enums.ml
ocamlfind ocamlc -package zarith -i z3native.ml > z3native.mli
ocamlfind ocamlc -package zarith -c z3native.mli
ocamlfind ocamlc -package zarith -c z3native.ml
ocamlfind ocamlc -package zarith -c z3.mli
ocamlfind ocamlc -package zarith -c z3.ml
ocamlfind ocamlopt -package zarith -c z3enums.ml
ocamlfind ocamlopt -package zarith -c z3native.ml
ocamlfind ocamlopt -package zarith -c z3.ml
ocamlfind ocamlc -package zarith -ccopt "-fPIC -I$z3_package/include -I." -c z3native_stubs.c
ocamlmklib -o z3ml -I . -L"$z3_package/lib" z3native_stubs.o z3enums.cmo z3native.cmo z3.cmo -lz3 -lstdc++
ocamlmklib -o z3ml -I . -L"$z3_package/lib" z3native_stubs.o z3enums.cmx z3native.cmx z3.cmx -lz3 -lstdc++
ocamlfind ocamlopt -package zarith -linkall -shared -o z3ml.cmxs -I . z3ml.cmxa
"$experiment_dir/venv/bin/python" -c 'from pathlib import Path; Path("META").write_text(Path("META.in").read_text().replace("@Z3_VERSION_STRING@", "4.15.3"))'
ocamlfind install Z3 META z3enums.mli z3enums.cmi z3enums.cmx \
  z3native.mli z3native.cmi z3native.cmx z3.mli z3.cmi z3.cmx \
  libz3ml.a z3ml.a z3ml.cma z3ml.cmxa z3ml.cmxs dllz3ml.so
fi
cd "$experiment_dir/icra"
if git apply --unidiff-zero --check "$experiment_dir/ArithExe/experiments/linux/icra-libraries-only.patch"; then
  git apply --unidiff-zero "$experiment_dir/ArithExe/experiments/linux/icra-libraries-only.patch"
else
  git apply --unidiff-zero --reverse --check "$experiment_dir/ArithExe/experiments/linux/icra-libraries-only.patch"
fi
# Do not build unrelated legacy NWA command-line utilities (not used by ICRA).
(cd WALi-OpenNWA && scons strong_warnings=0 icra-libs -Q)
make -j1 duet
# OCaml's dependency flags can put /usr/lib before the Z3 binding's -L flag.
# Give its native linker the matching pip Z3 directory first, not system Z3.
(cd duet && ocamlbuild -use-ocamlfind -tag 'runtime_variant(_pic)' \
  -lflags "-without-runtime,-ccopt,-L$experiment_dir/venv/lib/python3.14/site-packages/z3/lib" \
  duet/libduet.native.so)
make -j1 _build/icra.o _build/icra_callbacks.o _build/ire.o _build/ire_callbacks.o
# Exactly one modern OCaml runtime, shared with the duet library.
g++ -g -rdynamic -Wl,--no-as-needed -o icra _build/icra.o _build/ire_callbacks.o _build/ire.o _build/icra_callbacks.o \
  "$experiment_dir/icra/duet/_build/duet/libduet.native.so" \
  "$experiment_dir/icra/WALi-OpenNWA/lib64/libwali.so" \
  "$experiment_dir/icra/WALi-OpenNWA/lib64/libwalidomains.so" "$(ocamlc -where)/libasmrun_shared.so" \
  "$experiment_dir/venv/lib/python3.14/site-packages/z3/lib/libz3.so" \
  -lglog -lrt -ldl -lm \
  -Wl,-rpath,"$experiment_dir/icra/duet/_build/duet" \
  -Wl,-rpath,"$experiment_dir/icra/WALi-OpenNWA/lib64" \
  -Wl,-rpath,"$(ocamlc -where)"
opam list --installed --columns=name,version > "$experiment_dir/logs/icra-opam-inventory.txt"
ldd icra > "$experiment_dir/logs/icra-library-inventory.txt"
./icra --help
